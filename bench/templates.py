def visual_terms(caption: str, exclude: str) -> list[str]:
    """The content words a caption adds beyond its subject's own name.

    Extracted by rule rather than by a model, so the gold for a visual question is
    computed like every other gold here. Terms the entity name already supplies are
    removed: answering "Shiroishi washi" to a question about Shiroishi washi's appearance
    would otherwise count as describing it.
    """
    drop = {w.lower() for w in re.findall(r"\w+", exclude)} | _STOP
    visual, other, seen = [], [], set()
    for w in re.findall(r"[A-Za-z][\w-]+", caption):
        k = w.lower()
        if k in drop or k in seen or len(w) <= 3:
            continue
        seen.add(k)
        # A visual predicate is the part only the picture supplies. Ordering by position
        # in the caption instead would promote whatever the sentence happened to open
        # with -- "Lotus Sutra segment lavishly" over "gold silver sprinkled" -- and the
        # answer would then be gradeable from the chain alone.
        (visual if _VISUAL.match(w) else other).append(w)
    return visual + other


def t_mm_chain(g: GraphIndex, rng: random.Random, k: int = 2):
    """A reasoning chain whose final answer is only in the endpoint's photograph.

    Every other template draws its gold from T, so text evidence alone always suffices
    and a perfect-knowledge upper bound can gain nothing from images -- which made A_img
    look useful only as a way *into* the graph. Here the chain is traversed over triples
    but the question it answers is settled by the picture at its end: a colour, a weave,
    a pattern, none of which any triple records. Text-only evidence reaches the right
    entity and still cannot answer, so Know+ exceeds Know by construction rather than by
    hope.

    Built backwards from an illustrated endpoint: a forward walk reaches one only by luck.
    """
    if not hasattr(g, "_vis_terminals"):
        cands = []
        for n in g.mm:
            if n in g.hubs:
                continue
            for img in g.E[n]["attributes"]["img"]:
                c = img.get("caption") or ""
                if len(c.split()) >= 10 and _VISUAL.search(c):
                    terms = visual_terms(c, n)
                    if len(terms) >= 4:
                        cands.append((n, img, c, terms))
        g._vis_terminals = cands
    cands = g._vis_terminals
    if not cands:
        return None

    for _ in range(80):
        end, img, caption, terms = cands[rng.randrange(len(cands))]
        chain, edges, cur = [end], [], end
        for _ in range(k):
            # g.inn stores (head, relation), not (relation, head)
            # built backwards, but read forwards: the question describes the step from h
            # to cur, so h must reach cur and nothing else under r. Without this the walk
            # is offered a sibling of `cur` that the description fits just as well.
            back = [(h, r) for h, r in g.inn.get(cur, [])
                    # The confusable-relation test is not applied here, only `unforked`.
                    # Requiring all three of unforked, unconfusable and an endpoint whose
                    # caption is usable leaves 152 items, and this is the one type that
                    # shows Know+ above Know -- the effect is +.39, but it needs a sample
                    # to be read off. A wrong turn here is also cheaper than on a text
                    # chain: the answer lives in a photograph, so a step into a sibling
                    # that carries no image fails outright rather than yielding a
                    # confident wrong answer.
                    if h not in chain and g.is_core(r) and h not in g.hubs
                    and g.unforked(h, r)]
            if not back:
                break
            h, r = rng.choice(back)
            edges.append([h, r, cur])
            chain.append(h)
            cur = h
        if len(edges) < k:
            continue
        edges.reverse()
        # the caption is stripped from the item's copy of the image: it is the answer,
        # and a model reading it off the record would not have looked at anything
        q_img = {kk: vv for kk, vv in img.items() if kk != "caption"}
        return QAItem(
            qid="", type="mm_chain", answer_atoms=terms[:6],
            gold_triples=edges, hops=k + 1,
            spec={"mode": "visual_terminal", "start": chain[-1], "path": edges,
                  "endpoint": end, "caption": caption, "hide_caption": True},
            images=[{"entity": end, **q_img}],
        )
    return None


def t_aggregation(g: GraphIndex, rng: random.Random):
    """Whole-graph reasoning: neither mode can be answered by following a path.

    `extremum` (min over origin_year, argmax over relation objects) and `absence`
    (set difference) were separate types at first. Extremum was dropped as its own
    category because the graph holds only a handful of genuinely distinct aggregates
    — a five-item type is not a category, it is a rounding error in the type table.
    They are merged rather than deleted because they share the property that matters:
    the answer exists nowhere in the graph until the whole triple set is scanned, so
    a path-retrieval method has no structural advantage on them. That is exactly why
    the benchmark needs to keep them.
    """
    if rng.random() < 0.15:
        item = _extremum(g, rng)
        if item is not None:
            return item
    return _absence(g, rng)


